// Типы бейджа (контракт бэка от 23.10.2026, ADR бэка common/0045)
// Элемент стека баджей приходит готовым от бэка: текст, цвет-пресет, иконка, ссылка.

/**
 * Пресеты цвета плашки бэка: ключи классов шаблона (`benefit--red` и т.п.).
 * Набор иконок шаблона совпадает с пресетами 1:1 (ADR 0008) — отсюда один
 * источник значений и для цвета, и для `icon_key`.
 * Новый пресет на бэке — новое значение здесь и новый класс на фронте.
 */
export const BADGE_COLORS = ["red", "gold", "green"] as const;

/** Пресет цвета плашки. */
export type BadgeColor = (typeof BADGE_COLORS)[number];

/** Ключ иконки плашки — из набора шаблона (совпадает с пресетами цвета). */
export type BadgeIconKey = BadgeColor;

/**
 * Стек баджей сущности (товар → модель → бренд): порядок и состав собирает бэк,
 * фронт не фильтрует и не сортирует.
 */
export interface Badge {
  /** Текст плашки — готовый от бэка. */
  text: string;
  /** Цвет-пресет плашки. */
  color: BadgeColor;
  /** Ключ иконки из набора фронта; null — иконка по цвету. */
  icon_key: string | null;
  /** Ссылка плашки; null — без ссылки. */
  link: string | null;
  /** Морф-алиас источника (product | model | brand | site) — служебное поле, не выводится. */
  owner_type: string;
  /** Имя источника — служебное поле, не выводится. */
  owner_name: string | null;
}
